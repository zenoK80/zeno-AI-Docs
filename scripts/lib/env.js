//----------------------------------------------------------------------------------
// [핵심 개념]
// 1. .env.local: API 키를 코드 밖에 두는 파일 (gitignore 대상이라 커밋 안 됨)
// 2. process.env: Node 전역 환경변수 객체 — 여기 넣어두면 모든 모듈이 읽을 수 있음
// 3. dotenv 패키지 없이 정규식으로 KEY=VALUE 줄을 직접 파싱
//----------------------------------------------------------------------------------
const fs = require('fs')
const path = require('path')

//----------------------------------------------------------------------------------
// [1] 프로젝트 루트 경로
// - 역할: 이 파일 위치(scripts/lib)에서 두 단계 위 = 프로젝트 루트
// - 다른 모듈이 경로 계산할 때 재사용하도록 export
//----------------------------------------------------------------------------------
const ROOT = path.join(__dirname, '..', '..')

//----------------------------------------------------------------------------------
// [2] .env.local 로딩
// - 역할: "KEY=VALUE" 줄을 읽어 process.env에 등록
// - 규칙: 터미널에서 직접 지정한 환경변수가 이미 있으면 그쪽을 우선
// - split(/\r?\n/): Windows(CRLF)·유닉스(LF) 줄바꿈 모두 처리
//----------------------------------------------------------------------------------
function loadEnvLocal() {
  const envPath = path.join(ROOT, '.env.local')
  if (!fs.existsSync(envPath)) return
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
    if (m && !(m[1] in process.env)) {
      // 값을 "..." 나 '...' 로 감쌌어도 벗겨서 저장
      process.env[m[1]] = m[2].replace(/^["']|["']$/g, '')
    }
  }
}

module.exports = { ROOT, loadEnvLocal }
