//----------------------------------------------------------------------------------
// [핵심 개념]
// 1. 단계 모듈 인터페이스: { name, provider, run(dirs, opts, chat) } 로 통일
//    → 진입점(generate-doc.js)은 단계 내용을 몰라도 순서대로 실행만 하면 됨
// 2. 원래 1단계는 대화형이지만, 일괄 실행에서는 대화가 불가능하므로
//    "질문 대신 합리적인 초안을 제안하라"로 지시를 바꿔서 태움
// 3. 생성된 초안은 반드시 사람이 검토·수정할 것 (뒤 4개 단계가 이 파일을 믿고 달림)
//----------------------------------------------------------------------------------
const path = require('path')
const { readInstruction, writeOut } = require('../lib/files')

module.exports = {
  name: '학습방향',
  provider: 'grok',

  //--------------------------------------------------------------------------------
  // [1] 실행
  // - 입력: 없음 (과목명·주제만으로 시작하는 첫 단계)
  // - 출력: prompts/plan/[과목]/01_학습방향.md
  // - opts.topic: 폴더명과 다른 상세 주제를 줄 때 사용 (--topic "Git 기초부터 실무까지")
  //--------------------------------------------------------------------------------
  async run(dirs, opts, chat) {
    //------------------------------------------------------------------------------
    // [0] 이어하기 보호: 이미 산출물이 있으면 건너뜀 (다시: 예 / --all 이면 재생성)
    //     → 작업지시서를 다시 실행해도 완료된 단계에 API 비용이 안 나감
    //------------------------------------------------------------------------------
    const fs = require('fs')
    const outPath = path.join(dirs.plan, '01_학습방향.md')
    if (!opts.all && fs.existsSync(outPath)) {
      return console.log('  건너뜀: 01_학습방향.md 이 이미 있음 (다시 만들려면 "다시: 예")')
    }

    const instruction = readInstruction('01_학습방향.md')
    const topic = opts.topic || opts.subject
    const result = await chat(
      instruction,
      [
        `과목: ${topic}`,
        '',
        '위 과목에 대해 지시문의 6개 항목(대상 독자/학습 목표/범위/깊이/실습 비중/배치 경로)을',
        '전부 채운 학습 방향 문서 초안을 산출물 형식대로 작성하라.',
        '사용자와 대화할 수 없는 일괄 실행 상황이므로, 질문 대신 합리적인 초안을 제안하라.',
        opts.path
          ? `배치 경로는 정확히 "${opts.path.replace(/\/$/, '')}/" 로 하라.`
          : `배치 경로의 과목 폴더명은 "${opts.subject}"를 사용하라.`,
      ].join('\n')
    )
    writeOut(path.join(dirs.plan, '01_학습방향.md'), result)
  },
}
