--------------------------------------------------------------------------------
-- 적재 확인용 SELECT
--   아래 결과가 모두 정상적으로 나오면 seed 적재가 완료된 것이다.
--------------------------------------------------------------------------------

-- 1) 사원 4명이 모두 보이는지 (08·09·15편 공용 데이터)
SELECT * FROM 사원 ORDER BY 사원번호;

-- 2) EMP·DEPT 조인 결과가 16편 INNER JOIN 예제와 같은 3행인지
SELECT E.NAME, D.DNAME
FROM EMP E
JOIN DEPT D ON E.DEPT_ID = D.DEPT_ID;

-- 3) 19편 RANK 예제를 그대로 돌려 순위가 매겨지는지
SELECT 사번, 이름, 부서, 급여,
       RANK() OVER (PARTITION BY 부서 ORDER BY 급여 DESC) AS 순위
FROM 직원;

-- 4) 전체 테이블이 22개 모두 만들어졌는지 개수로 확인
SELECT COUNT(*) AS 생성된_테이블_수
FROM USER_TABLES
WHERE TABLE_NAME IN (
  '사원', '부서', 'EMP', 'DEPT', 'DEPT_LIST',
  '회원', '임시로그', '재고', '재고이력',
  '직원', '성적', '급여', '주문', '주문상세',
  '고객', '결제', '계좌', '학과', '우수회원',
  'TAB1', '매출', '결제내역'
);
-- 22가 나와야 정상이다.
