-- SQLD 학습 공통 실습 데이터 (seed.sql)
--------------------------------------------------------------------------------
--
-- 이 스크립트는 무엇을 만드는가
--   content/자격증/SQLD/ 07~25편 본문에 등장하는 예제 SQL을 그대로 복사해
--   실행할 수 있도록, 그 예제들이 참조하는 테이블 22종을 전부 만들고
--   문서에 적힌 "실행 결과" 표가 재현되도록 데이터를 채워 넣는다.
--
-- 어떻게 실행하는가 (자세한 절차는 31편 부록 참고)
--   1) DBeaver 등 SQL 클라이언트에서 이 파일 전체를 열고 "스크립트 실행"
--      (SQL Editor > Execute SQL Script, 단건 실행이 아니다)으로 한 번에 돌린다.
--   2) 맨 아래 확인용 SELECT 결과가 정상적으로 나오면 적재가 끝난 것이다.
--   3) 이후 07~25편의 ```sql 코드 블록을 그대로 복사해 실행하면서 문서의
--      "실행 결과" 표와 대조하며 읽는다.
--
-- 왜 같은 개념인데 테이블이 여러 개인가 (사원 / EMP / 직원 / 성적 등)
--   이 과목은 19개 편이 나눠서 집필되었고, 각 편은 그 시점에 배우는 개념을
--   가장 잘 보여주는 예제 테이블을 독립적으로 골랐다. 그 결과 "사원 = EMP =
--   직원"처럼 같은 개념을 부르는 이름이 편마다 다르다. 이걸 하나로 통일해
--   19개 편의 SQL과 본문 결과표를 전부 고치는 방법도 있었지만, 손대는 범위가
--   너무 넓어 오히려 결과표가 틀어질 위험이 컸다(자세한 근거는
--   prompts/plan/SQLD/01_학습방향.md의 「실습 환경 방침」 참고). 그래서 이
--   스크립트는 "문서를 seed에 맞추는" 대신 "seed를 문서에 맞춘다" — 07~25편에
--   실제로 등장하는 22개 테이블을 전부, 그 이름 그대로 만든다.
--
-- 사원 테이블에 대한 안내 (가장 많이 재사용되는 테이블)
--   `사원`은 08·09·13·14·15·22·23·25편에서 총 8번 재사용되는데, 그중 08·09·15편은
--   서로 다른 컬럼(부서번호/커미션/보너스)을 같은 4명에게 매핑하는 것이라
--   하나의 표로 완전히 통합할 수 있었다(그 결과가 아래 사원 테이블이다).
--   반면 22편(Top-N/ROWNUM)과 23편(PIVOT)은 문서 안에서 독자적인 5명짜리
--   예시 데이터를 새로 등장시키는데, 이 두 편의 데이터셋은 08·09·15편의
--   4명 데이터셋과 인원 구성 자체가 달라 한 테이블로 동시에 재현할 수
--   없다(수학적으로 불가능 — 같은 이름의 테이블을 조건 없이 조회하는 여러
--   편이 서로 다른 행 개수·행 구성을 요구하기 때문). 그래서 이 스크립트는
--   Quiz 정답이 구체적인 숫자에 의존하는 08·09·15편을 정본으로 채택했다.
--   22·23·25편도 이 사원 테이블로 실습 자체는 가능하지만(SQL 문법과 동작
--   원리는 동일하게 확인된다), 문서 본문에 적힌 구체적인 예시 숫자·부서명과
--   정확히 일치하지는 않는다. 이 세 편의 Quiz는 특정 출력값이 아니라 SQL의
--   동작 원리(ROWNUM 리셋 규칙, PIVOT/UNPIVOT 방향, DECODE와 CASE의 차이)를
--   물으므로 학습에는 지장이 없다.
--   같은 이유로 19편의 NTILE(8행) 예시, 24편의 김대리(권한 부여 대상 사용자)도
--   완전히 재현하지는 못한다. 24편은 테이블이 아니라 DB 계정이 필요한
--   편이므로, seed에는 포함하지 않았다 — 31편에서 별도로 안내한다.
--
-- 몇몇 테이블(학과·회원·임시로그)은 10·12편 본문에서 "CREATE TABLE ..."
--   자체가 학습 목표인 예제로 등장한다. 이 테이블들은 이미 이 seed가
--   만들어 두므로, 그 편을 읽다가 문서의 CREATE TABLE 문을 그대로 실행하면
--   "이미 존재하는 이름입니다(ORA-00955)" 오류가 나는 것이 정상이다. 오류
--   메시지를 무시하고 그다음 INSERT·ALTER·DELETE 문부터 이어서 실행하면 된다.
--
-- Oracle Database Free 23ai(gvenzl/oracle-free) 기준으로 작성했다.
-- VARCHAR2 / NUMBER / DATE / TO_DATE 등 Oracle 전용 문법을 사용한다.
--
-- 재실행 가능하도록, 맨 앞에서 기존 테이블을 전부 지운다. Oracle은
-- 테이블이 없는 상태에서 DROP TABLE을 실행하면 오류(ORA-00942)로 멈추므로,
-- PL/SQL 블록으로 감싸 그 오류만 무시하고 넘어가게 처리했다.
--------------------------------------------------------------------------------

BEGIN
  FOR t IN (
    SELECT COLUMN_VALUE AS tname
    FROM TABLE(SYS.ODCIVARCHAR2LIST(
      '사원', '부서', 'EMP', 'DEPT', 'DEPT_LIST',
      '회원', '임시로그', '재고', '재고이력',
      '직원', '성적', '급여', '주문', '주문상세',
      '고객', '결제', '계좌', '학과', '우수회원',
      'TAB1', '매출', '결제내역'
    ))
  )
  LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.tname || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
          RAISE;
        END IF;
    END;
  END LOOP;
END;
