--------------------------------------------------------------------------------
-- 22·23편 전용 보조 스크립트 (seed-22-23.sql)
--------------------------------------------------------------------------------
--
-- 이 스크립트는 무엇을 하는가
--   22편(Top N·ROWNUM·계층형 질의)과 23편(PIVOT과 기타 활용 구문) 본문에
--   나오는 예제 SQL이 "문서에 적힌 결과 그대로" 재현되도록, 공통 seed.sql이
--   만들어 둔 `사원` 테이블을 이 두 편 전용 데이터로 통째로 교체한다.
--
-- 왜 필요한가 (반드시 읽을 것)
--   seed.sql 맨 위 주석에 적혀 있듯, `사원` 테이블은 08·09·15편(4명 데이터셋)과
--   22·23편(문서 안의 5명 데이터셋)이 서로 다른 인원 구성을 요구해서 하나의
--   표로 동시에 재현할 수 없다. seed.sql은 08·09·15편을 정본으로 채택했으므로,
--   22·23편의 예제를 문서에 적힌 숫자 그대로 확인하려면 이 스크립트로 `사원`
--   테이블을 잠시 22·23편 전용 데이터로 바꿔야 한다.
--
-- *** 중요: 이 스크립트를 실행하면 08·09·15편 실습 데이터가 사라진다 ***
--   이 스크립트는 `사원` 테이블을 DROP하고 다시 만든다. 그래서 이 스크립트를
--   실행한 뒤에는 08·09·15편의 예제(부서번호 조인, 커미션 NULL 집계, 보너스
--   그룹 함수)가 더 이상 문서와 같은 결과를 주지 않는다. 08·09·15편으로
--   돌아가서 실습하려면 `public/sqld/seed.sql`을 다시 실행해 `사원` 테이블을
--   원래 상태로 되돌려야 한다. 즉 순서는 다음과 같다.
--     seed.sql 실행 → 08·09·15편 실습 → (22·23편으로 넘어갈 때) 이 파일 실행
--     → 22·23편 실습 → (다시 08·09·15편으로 돌아갈 때) seed.sql 재실행
--   `매출`, `직원`, `급여` 등 사원 이외의 테이블은 이 스크립트가 건드리지
--   않으므로, 23편의 UNPIVOT 예제(매출 테이블 사용)는 seed.sql이 이미 만들어
--   둔 테이블을 그대로 쓴다.
--
-- 데이터 설계 메모
--   `사원` 테이블 하나에 22편이 필요로 하는 두 가지 예제(급여 기준 Top N,
--   상사-사원 계층)와 23편이 필요로 하는 예제(부서·직급별 연봉 PIVOT)를
--   모두 담아야 한다. 세 가지가 서로 다른 인원·구조를 요구하므로, 아래처럼
--   역할을 나누어 섞었다.
--     - 사번 101~105: 22편 ROWNUM/Top N 예제의 5명(급여 3000/5000/4000/
--       2000/4500)이면서 동시에 23편 PIVOT 예제의 5명(부서·직급·연봉)이기도
--       하다. 이 5명의 상사사번은 -1(테이블에 존재하지 않는 사번)로 두어,
--       계층형 질의에 전혀 끼어들지 않게 했다(상사사번이 NULL이 아니므로
--       START WITH의 루트도 되지 않고, 사번 -1이 없으므로 누구의 자식으로도
--       연결되지 않는다).
--     - 사번 100~600: 22편 계층형 질의(CONNECT BY) 예제의 조직도 6명이다.
--       급여를 0으로 낮게 주어 Top N(급여 내림차순) 결과에 절대 끼어들지
--       않게 했다(0은 위 5명의 최저 급여 2000보다 작다).
--   이렇게 하면 아래 확인용 SELECT처럼 조건을 살짝만 걸어도(부서 IS NOT
--   NULL, 상사사번 IS NULL 등) 각 편의 예제가 문서와 동일한 결과를 낸다.
--
-- 재실행 가능하도록, 맨 앞에서 기존 `사원` 테이블을 지운다. 테이블이 없는
-- 상태에서 DROP TABLE을 실행하면 오류(ORA-00942)가 나므로, PL/SQL 블록으로
-- 감싸 그 오류만 무시하고 넘어가게 처리했다(seed.sql과 동일한 방식).
--------------------------------------------------------------------------------

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE 사원 CASCADE CONSTRAINTS PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN
      RAISE;
    END IF;
END;
/

--------------------------------------------------------------------------------
-- 사원 -- 22편(ROWNUM/Top N, CONNECT BY 계층형 질의)·23편(PIVOT) 전용 데이터.
--   08·09·15편의 사원 테이블과는 완전히 다른 구조와 데이터이므로, 이 스크립트
--   실행 중에는 08·09·15편 실습을 하지 말 것(위 안내 참고).
--------------------------------------------------------------------------------
CREATE TABLE 사원 (
  사번     NUMBER        PRIMARY KEY,
  이름     VARCHAR2(20)  NOT NULL,
  급여     NUMBER,                -- 22편 ROWNUM/Top N 예제
  상사사번 NUMBER,                -- 22편 CONNECT BY 계층형 질의 예제
  부서     VARCHAR2(20),          -- 23편 PIVOT 예제
  직급     VARCHAR2(20),          -- 23편 PIVOT 예제
  연봉     NUMBER                 -- 23편 PIVOT 예제
);

-- 22편 ROWNUM/Top N 예제(5명, 급여)이자 23편 PIVOT 예제(부서·직급·연봉)의
-- 원본 데이터. 상사사번을 -1로 두어 계층형 질의에서 완전히 제외되게 했다.
INSERT INTO 사원 VALUES (101, '김민준', 3000, -1, '인사팀', '사원', 3000);
INSERT INTO 사원 VALUES (102, '이서연', 5000, -1, '인사팀', '대리', 4000);
INSERT INTO 사원 VALUES (103, '박도윤', 4000, -1, 'IT팀',   '사원', 3200);
INSERT INTO 사원 VALUES (104, '최지우', 2000, -1, 'IT팀',   '과장', 5500);
INSERT INTO 사원 VALUES (105, '정하늘', 4500, -1, 'IT팀',   '대리', 4300);

-- 22편 CONNECT BY 계층형 질의 예제(조직도 6명). 급여를 0으로 낮게 두어
-- Top N 예제 결과에 섞이지 않게 했고, 부서·직급·연봉은 PIVOT 예제와
-- 무관하므로 NULL로 둔다.
INSERT INTO 사원 VALUES (100, '대표',   0, NULL, NULL, NULL, NULL);
INSERT INTO 사원 VALUES (200, '김부장', 0, 100,  NULL, NULL, NULL);
INSERT INTO 사원 VALUES (300, '이과장', 0, 200,  NULL, NULL, NULL);
INSERT INTO 사원 VALUES (400, '박대리', 0, 200,  NULL, NULL, NULL);
INSERT INTO 사원 VALUES (500, '최사원', 0, 300,  NULL, NULL, NULL);
INSERT INTO 사원 VALUES (600, '정사원', 0, 300,  NULL, NULL, NULL);

COMMIT;

--------------------------------------------------------------------------------
-- 적재 확인용 SELECT
--   아래 세 결과가 모두 문서의 결과와 일치하면 22·23편 전용 데이터로 정상
--   교체된 것이다.
--------------------------------------------------------------------------------

-- 1) 급여 상위 3명 -- 이서연(5000), 정하늘(4500), 박도윤(4000) 순서로 나와야
--    22편의 인라인뷰 Top N 예제와 일치한다.
SELECT *
FROM (SELECT * FROM 사원 ORDER BY 급여 DESC)
WHERE ROWNUM <= 3;

-- 2) 조직도 계층 -- 대표(LEVEL 1)부터 정사원(LEVEL 4)까지 6행이 나와야
--    22편의 CONNECT BY 예제와 일치한다.
SELECT LEVEL, 사번, 이름, 상사사번
FROM 사원
START WITH 상사사번 IS NULL
CONNECT BY PRIOR 사번 = 상사사번
ORDER BY LEVEL, 사번;

-- 3) 부서·직급별 연봉 PIVOT -- 인사팀·IT팀 2행이 나와야 23편의 PIVOT
--    예제와 일치한다(사번·상사사번 등은 인라인뷰로 제외해야 부서 하나로만
--    그룹핑된다 -- 22편에서 배운 인라인뷰가 여기서도 그대로 쓰인다).
SELECT *
FROM (SELECT 부서, 직급, 연봉 FROM 사원 WHERE 부서 IS NOT NULL)
PIVOT (
  SUM(연봉) FOR 직급 IN ('사원' AS 사원, '대리' AS 대리, '과장' AS 과장)
);
